export const translations = { es, en };

export function normalizeLang(lang) {
  return lang === "en" ? "en" : DEFAULT_LANG;
}

// Devuelve una función t(key, params?) para el idioma dado.
// Interpola {placeholders} y cae al español y luego a la clave.
export function getT(lang) {
  const dict = translations[normalizeLang(lang)];
  return (key, params) => {
    let text = dict[key] ?? translations.es[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  };
}
